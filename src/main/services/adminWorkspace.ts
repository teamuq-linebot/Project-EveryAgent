/**
 * adminWorkspace — 佈署 `~/.teamuq` 管理工作區（plan_v1 §12 U6 / Part B）。
 *
 * app 啟動（whenReady、reconcile 之後）呼叫 `ensureAdminWorkspace()`：
 *   - 寫 `~/.teamuq/scripts/*.mjs`（查任務 / 查打卡 / 通用唯讀查詢 / 備份 DB）。
 *   - 寫 `~/.teamuq/CLAUDE.md`（目錄說明 + DB schema 摘要 + scripts 用法 + 安全須知）。
 *
 * **managed 檔案策略**：每個 managed 檔頭標記 MANAGED_MARKER；每次啟動「覆寫」這些
 * managed 檔（檔頭仍是該標記者才覆寫；使用者改過頭的檔不動，避免覆掉手改）。目錄裡
 * 使用者自加的其他檔一律不動。
 *
 * ⚠️ ABI 陷阱：scripts 為獨立 `.mjs`，**絕不可** require app 的 better-sqlite3
 * （Electron ABI ≠ 系統 Node ABI）。一律用 `node:sqlite`（Node 22+ 內建）。
 * 因此這些 scripts 用「系統 node」直接跑：`node ~/.teamuq/scripts/tasks.mjs`。
 */

/** managed 檔案標記（檔頭首行）。檔頭是此標記者，啟動時才覆寫。 */
const MANAGED_MARKER = 'auto-generated by teamuq-electron, do not edit'
const MANAGED_MARKER_JS = `// ${MANAGED_MARKER}`
const MANAGED_MARKER_MD = `<!-- ${MANAGED_MARKER} -->`

/** ~/.teamuq 解析：與 repo / migrate / secretStore 同一慣例（TEAMUQ_HOME 可覆寫測試）。 */
function teamuqDir(): string {
  const home = process.env['TEAMUQ_HOME'] || os.homedir()
  return path.join(home, '.teamuq')
}

