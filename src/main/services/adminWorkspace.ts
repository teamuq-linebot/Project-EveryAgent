// managed 檔案寫入（每次啟動覆寫 managed 檔；非 managed / 手改檔不動）
// ---------------------------------------------------------------------------

interface ManagedFile {
  /** 相對 ~/.teamuq 的路徑。 */
  rel: string
  content: string
  /** 用於判斷既有檔是否仍為 managed（檔頭含此標記）。 */
  marker: string
}

const MANAGED_FILES: ManagedFile[] = [
  { rel: 'scripts/_db.mjs', content: `${MANAGED_MARKER_JS}\n${SCRIPT_DB_HELPER}`, marker: MANAGED_MARKER },
  { rel: 'scripts/query.mjs', content: SCRIPT_QUERY, marker: MANAGED_MARKER },
  { rel: 'scripts/tasks.mjs', content: SCRIPT_TASKS, marker: MANAGED_MARKER },
  { rel: 'scripts/punches.mjs', content: SCRIPT_PUNCHES, marker: MANAGED_MARKER },
  { rel: 'scripts/backup-db.mjs', content: SCRIPT_BACKUP, marker: MANAGED_MARKER },
  { rel: 'CLAUDE.md', content: CLAUDE_MD, marker: MANAGED_MARKER },
]

const STALE_MANAGED_FILES = ['scripts/platforms.mjs']

/**
 * 寫一個 managed 檔：
 *   - 不存在 → 寫。
 *   - 存在且檔頭含 marker（仍是 managed）→ 內容不同才覆寫（冪等省 I/O）。
 *   - 存在但檔頭無 marker（使用者改成自己的）→ **不動**（保護手改）。
 */
function writeManaged(baseDir: string, f: ManagedFile): 'written' | 'unchanged' | 'skipped-user' {
  const abs = path.join(baseDir, f.rel)
  fs.mkdirSync(path.dirname(abs), { recursive: true })

  if (fs.existsSync(abs)) {
    let existing = ''
    try {
      existing = fs.readFileSync(abs, 'utf8')
    } catch {
      existing = ''
    }
    // 檔頭（前 200 字內）不含 marker → 使用者接管，跳過。
    if (!existing.slice(0, 200).includes(f.marker)) return 'skipped-user'
    if (existing === f.content) return 'unchanged'
  }

  fs.writeFileSync(abs, f.content, 'utf8')
  return 'written'
}

function removeStaleManaged(baseDir: string, rel: string): 'removed' | 'absent' | 'skipped-user' {
  const abs = path.join(baseDir, rel)
  if (!fs.existsSync(abs)) return 'absent'
  let existing = ''
  try {
    existing = fs.readFileSync(abs, 'utf8')
  } catch {
    return 'skipped-user'
  }
  if (!existing.slice(0, 200).includes(MANAGED_MARKER)) return 'skipped-user'
  fs.rmSync(abs, { force: true })
  return 'removed'
}

export interface AdminWorkspaceReport {
  ok: boolean
  dir: string
  written: string[]
  unchanged: string[]
  removed: string[]
  skippedUser: string[]
  error?: string
}

/**
 * 佈署 / 對齊 `~/.teamuq` 管理工作區的 managed 檔（scripts + CLAUDE.md）。
 * 冪等、容錯：任何 I/O 失敗只回報、不丟例外（啟動不可被此卡死）。
 */
export function ensureAdminWorkspace(): AdminWorkspaceReport {
  const dir = teamuqDir()
  const report: AdminWorkspaceReport = {
    ok: true,
    dir,
    written: [],
    unchanged: [],
    removed: [],
    skippedUser: [],
  }
  try {
    fs.mkdirSync(dir, { recursive: true })
    for (const f of MANAGED_FILES) {
      const outcome = writeManaged(dir, f)
      if (outcome === 'written') report.written.push(f.rel)
      else if (outcome === 'unchanged') report.unchanged.push(f.rel)
      else report.skippedUser.push(f.rel)
    }
    for (const rel of STALE_MANAGED_FILES) {
      const outcome = removeStaleManaged(dir, rel)
      if (outcome === 'removed') report.removed.push(rel)
      else if (outcome === 'skipped-user') report.skippedUser.push(rel)
    }
  } catch (e) {
    report.ok = false
    report.error = e instanceof Error ? e.message : String(e)
  }
  return report
}

