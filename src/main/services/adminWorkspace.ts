const SCRIPT_PUNCHES = `${MANAGED_MARKER_JS}
// punches.mjs — 列打卡（近 N 天，含工時小計）。用法：node punches.mjs [天數=7]
import { openDb } from './_db.mjs'

const days = Math.max(1, parseInt(process.argv[2] || '7', 10) || 7)
const sinceIso = new Date(Date.now() - days * 86400000).toISOString()

const db = openDb(true)
try {
  const rows = db.prepare(\`
    SELECT punch_uid, session_id, task_id, type, name,
           started_at, ended_at, hours, status, ok, error, source_file, source_pos
    FROM punches
    WHERE created_at >= ?
    ORDER BY created_at DESC\`).all(sinceIso)

  if (rows.length === 0) { console.log(\`（近 \${days} 天無打卡）\`); process.exit(0) }
  let total = 0
  for (const r of rows) {
    const h = typeof r.hours === 'number' ? r.hours : 0
    total += h
    const okMark = r.ok === 1 ? '✓' : r.ok === 0 ? '✗' : '·'
    const src = r.source_file ? \`  src=\${r.source_file}:\${r.source_pos ?? '?'}\` : ''
    console.log(\`\${okMark} [\${r.type || '—'}] \${r.name || r.punch_uid}  \${h.toFixed(2)}h  \${r.started_at || ''}~\${r.ended_at || ''}  \${r.status || ''}\${r.error ? ' ERR:' + r.error : ''}\${src}\`)
  }
  console.error(\`(共 \${rows.length} 筆，工時小計 \${total.toFixed(2)} 小時 / 近 \${days} 天)\`)
} finally {
  db.close()
}
`

const SCRIPT_BACKUP = `${MANAGED_MARKER_JS}
// backup-db.mjs — wal_checkpoint(TRUNCATE) 後複製 teamuq.db 到 backups/（帶日期）。
// 用法：node backup-db.mjs    （任何寫入操作前都先跑這支留底）
import { DatabaseSync } from 'node:sqlite'
import os from 'node:os'
import path from 'node:path'
import fs from 'node:fs'

function teamuqDir() {
  if (process.env.TEAMUQ_DB) return path.dirname(process.env.TEAMUQ_DB)
  const home = process.env.TEAMUQ_HOME || os.homedir()
  return path.join(home, '.teamuq')
}

const dir = teamuqDir()
const src = process.env.TEAMUQ_DB || path.join(dir, 'teamuq.db')
if (!fs.existsSync(src)) {
  console.error('✗ 找不到 teamuq.db：' + src)
  process.exit(1)
}

// 先 checkpoint：把 WAL 收進主檔，複製單檔即完整快照（§2.11）。
const db = new DatabaseSync(src)
try {
  db.exec('PRAGMA wal_checkpoint(TRUNCATE)')
} catch (e) {
  console.error('（checkpoint 警告，續備份）：', e.message)
} finally {
  db.close()
}

const backupsDir = path.join(dir, 'backups')
fs.mkdirSync(backupsDir, { recursive: true })
const d = new Date()
const p2 = (n) => String(n).padStart(2, '0')
const stamp = \`\${d.getFullYear()}\${p2(d.getMonth() + 1)}\${p2(d.getDate())}-\${p2(d.getHours())}\${p2(d.getMinutes())}\${p2(d.getSeconds())}\`
const dest = path.join(backupsDir, \`teamuq-\${stamp}.db\`)
fs.copyFileSync(src, dest)
console.log('✓ 已備份：' + dest)
`

